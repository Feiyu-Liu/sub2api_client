import 'package:dio/dio.dart';
import 'package:retrofit/retrofit.dart';

part 'admin_ops_alert_wire_service.g.dart';

@RestApi()
abstract class AdminOpsAlertWireService {
  factory AdminOpsAlertWireService(Dio dio, {String? baseUrl}) =
      _AdminOpsAlertWireService;

  @GET('/api/v1/admin/ops/alert-rules')
  Future<HttpResponse<Object?>> listRules(
    @CancelRequest() CancelToken cancelToken,
    @DioOptions() Options options,
    @Header('Authorization') String? authorization,
    @Header('x-api-key') String? apiKey,
  );

  @POST('/api/v1/admin/ops/alert-rules')
  Future<HttpResponse<Object?>> createRule(
    @Body() Map<String, Object?> body,
    @CancelRequest() CancelToken cancelToken,
    @DioOptions() Options options,
    @Header('Authorization') String? authorization,
    @Header('x-api-key') String? apiKey,
  );

  @PUT('/api/v1/admin/ops/alert-rules/{id}')
  Future<HttpResponse<Object?>> updateRule(
    @Path('id') int id,
    @Body() Map<String, Object?> body,
    @CancelRequest() CancelToken cancelToken,
    @DioOptions() Options options,
    @Header('Authorization') String? authorization,
    @Header('x-api-key') String? apiKey,
  );

  @DELETE('/api/v1/admin/ops/alert-rules/{id}')
  Future<HttpResponse<Object?>> deleteRule(
    @Path('id') int id,
    @CancelRequest() CancelToken cancelToken,
    @DioOptions() Options options,
    @Header('Authorization') String? authorization,
    @Header('x-api-key') String? apiKey,
  );

  @GET('/api/v1/admin/ops/alert-events')
  Future<HttpResponse<Object?>> listEvents(
    @Queries() Map<String, dynamic> query,
    @CancelRequest() CancelToken cancelToken,
    @DioOptions() Options options,
    @Header('Authorization') String? authorization,
    @Header('x-api-key') String? apiKey,
  );

  @GET('/api/v1/admin/ops/alert-events/{id}')
  Future<HttpResponse<Object?>> getEvent(
    @Path('id') int id,
    @CancelRequest() CancelToken cancelToken,
    @DioOptions() Options options,
    @Header('Authorization') String? authorization,
    @Header('x-api-key') String? apiKey,
  );

  @PUT('/api/v1/admin/ops/alert-events/{id}/status')
  Future<HttpResponse<Object?>> updateEventStatus(
    @Path('id') int id,
    @Body() Map<String, Object?> body,
    @CancelRequest() CancelToken cancelToken,
    @DioOptions() Options options,
    @Header('Authorization') String? authorization,
    @Header('x-api-key') String? apiKey,
  );

  @POST('/api/v1/admin/ops/alert-silences')
  Future<HttpResponse<Object?>> createSilence(
    @Body() Map<String, Object?> body,
    @CancelRequest() CancelToken cancelToken,
    @DioOptions() Options options,
    @Header('Authorization') String? authorization,
    @Header('x-api-key') String? apiKey,
  );
}
